        if reference['workload_sha256']!=signature or digest(reference['matrix'])!=reference['matrix_sha256']:raise ValueError('Reference signature/data mismatch')
        case_record=dict(id=case['id'],workload_sha256=signature,reference_sha256=sha(refpath),comparison_key=digest([signature,reference['matrix_sha256'],report['timing_protocol']]),runs=[],passed=False)
