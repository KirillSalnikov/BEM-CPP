def digest(value):return hashlib.sha256(json.dumps(value,sort_keys=True,separators=(',',':'),allow_nan=False).encode()).hexdigest()
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def write(path,value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True);tmp=path.with_suffix(path.suffix+'.tmp');tmp.write_text(json.dumps(value,indent=2,allow_nan=False)+'\n');tmp.replace(path)
def capture(command,env=None):
    try:p=subprocess.run([str(v) for v in command],env=env,text=True,capture_output=True,timeout=30)
    except (OSError,subprocess.TimeoutExpired):return None
    return p.stdout.strip() if p.returncode==0 else None

def validate_matrix(matrix,angles):
    if len(matrix)!=angles:raise ValueError('Incomplete angular curve')
    for i,row in enumerate(matrix):
        if len(row)!=17 or not all(math.isfinite(v) for v in row):raise ValueError('Invalid Mueller matrix')
        if abs(row[0]-180*i/(angles-1))>1e-8 or row[1]<=0:raise ValueError('Invalid theta grid or M11')

def matrix_error(actual,reference):
    validate_matrix(actual,len(reference));validate_matrix(reference,len(reference))
    floor=max(row[1] for row in reference)*1e-12
    maximum=0.;squares=0.;norm=0.
    for a,b in zip(actual,reference):
        if abs(a[0]-b[0])>1e-10:raise ValueError('Different theta grids')
        maximum=max(maximum,max(abs(x-y)/max(b[1],floor) for x,y in zip(a[1:],b[1:])))
        squares+=sum((x-y)**2 for x,y in zip(a[1:],b[1:]));norm+=sum(y*y for y in b[1:])
    return dict(max_scaled_M11=maximum,relative_L2=math.sqrt(squares/norm))

def statistics_of(values):
    median=statistics.median(values);mad=statistics.median(abs(v-median) for v in values)
    return dict(n=len(values),median=median,min=min(values),max=max(values),mean=statistics.mean(values),MAD=mad,relative_MAD=mad/median if median else 0)

def wrapper(path):
    """Recognize the installer's literal wrappers, keeping venv symlinks intact."""
    path=Path(path).expanduser().absolute();env={}
    if not path.exists():raise RuntimeError('Executable missing: '+str(path))
    if path.read_bytes()[:4]==b'\x7fELF':return path,env
    for line in path.read_text().splitlines():
        if line.startswith('export '):
            name,value=line[7:].split('=',1)
            if name in ['LD_LIBRARY_PATH','PATH']:env[name]=shlex.split(value)[0]
        if line.startswith('exec '):
            args=shlex.split(line[5:]);return Path(args[0]).absolute(),env
    raise RuntimeError('Use a native executable or a wrapper generated by install_rtx50.py')

def numerical_files(source,program):
    paths=[]
    for folder in ['src']+(['third_party/mstm'] if program=='bem-cpp' else []):
        paths.extend(p for p in (source/folder).rglob('*') if p.is_file() and p.suffix.lower() in ['.c','.cpp','.cc','.cu','.h','.hpp','.cuh','.inc','.inl','.f','.f90','.f95'])
    if program=='bem-cpp':
        paths.extend((source/'tools').glob('muller_*demo.cpp'));paths.append(source/'tools/muller_tmatrix_fmm_server.cpp');paths.append(source/'tools/tmatrix_so3_mstm.f90')
        paths.extend((source/'scripts').glob('tmatrix*.py'));paths.append(source/'scripts/build_fmm_tmatrix.py')
    else:paths.append(source/'cpu/GpuSupportStub.cpp')
    return sorted(set(paths))

def build_info(args,suite):
    prefix=(args.prefix or Path.home()/'.local/opt'/suite['program']).expanduser().absolute()
    installation=prefix/'installation.json';manifest=json.loads(installation.read_text()) if installation.exists() else {}
    profile=suite['profiles'][args.profile]
    executable=args.binary or prefix/'bin'/profile['wrapper']
    if not executable.exists():executable=ROOT/profile['relative_binary']
    native,exports=wrapper(executable)
    source=None
    for parent in native.parents:
        if (parent/'src').is_dir() and (parent/'Makefile').exists():source=parent;break
    if source is None:raise RuntimeError('Cannot locate matching native sources; use an installer build')
    paths=numerical_files(source,suite['program'])
    h=hashlib.sha256()
    for p in sorted(set(paths)):h.update(str(p.relative_to(source)).encode()+b'\0'+p.read_bytes()+b'\0')
    env=dict(os.environ);env.update(exports)
    version=capture([native,'--version'],env)
    if not version:raise RuntimeError('Executable --version failed')
    if suite['program']=='mbs-fast':
        if args.profile.startswith('gpu') and ('CUDA ' not in version or 'precise-math' not in version or 'phase-build-fp64' not in version):raise RuntimeError('Benchmark requires precise GPU phase math')
        if args.profile=='gpu-fp32' and 'fp32-diffraction-storage' not in version:raise RuntimeError('Not an FP32 storage build')
        if args.profile=='gpu-fp64' and 'fp64-diffraction-storage' not in version:raise RuntimeError('Not an FP64 storage build')
        if args.profile=='cpu' and 'CPU double' not in version:raise RuntimeError('Not a CPU double build')
    python=args.python
    if python is None and (prefix/'bin/bem').exists():python=wrapper(prefix/'bin/bem')[0]
    python=Path(python or sys.executable).absolute()
    comments=capture(['readelf','--string-dump=.comment',native]) if shutil.which('readelf') else ''
    compiler_ids=sorted(set(re.findall(r'GCC:\s*([^\n]+)',comments or '')))
    components={};analysis={}
    if suite['program']=='bem-cpp':
        for name in ['muller_tmatrix_fmm_server','tmatrix_so3_mstm']:
            path=source/'bin'/name
            if not path.exists():raise RuntimeError('BEM pipeline component missing: '+str(path))
            components[name]=dict(path=str(path),sha256=sha(path))
            text=capture(['readelf','--string-dump=.comment',path]) if shutil.which('readelf') else ''
            compiler_ids=sorted(set(compiler_ids+re.findall(r'GCC:\s*([^\n]+)',text or '')))
        analysis=json.loads(capture([python,'-c','import sys,json,numpy,scipy;print(json.dumps(dict(python=sys.version,numpy=numpy.__version__,scipy=scipy.__version__)))']) or '{}')
        if not analysis:raise RuntimeError('BEM pipeline Python requires NumPy and SciPy')
    return dict(executable=str(executable),native_binary=str(native),binary_sha256=sha(native),components=components,analysis_environment=analysis,version=version,numerical_source_signature_schema=2,numerical_source_sha256=h.hexdigest(),host_compiler_build_ids=compiler_ids,source_root=str(source),python=str(python),exports=exports,installation=manifest)

def smi_path():return shutil.which('nvidia-smi') or ('/usr/lib/wsl/lib/nvidia-smi' if Path('/usr/lib/wsl/lib/nvidia-smi').exists() else None)
def gpu_sample(device):
    smi=smi_path()
    if not smi:return None
    fields=['temperature.gpu','utilization.gpu','memory.used','power.draw','clocks.sm','clocks.mem']
    text=capture([smi,'-i',str(device),'--query-gpu='+','.join(fields),'--format=csv,noheader,nounits'])
    if not text:return None
    values={}
    for name,value in zip(fields,text.splitlines()[0].split(',')):
        try:values[name]=float(value.strip())
        except ValueError:values[name]=None
    return dict(time=time.time(),**values)

def hardware(args,build):
    cpu={}
    for line in Path('/proc/cpuinfo').read_text().splitlines():
        if ':' in line:
            k,v=line.split(':',1)
            if k.strip()=='model name':cpu['model']=v.strip();break
    cpu['logical_cpus']=os.cpu_count();cpu['affinity']=sorted(os.sched_getaffinity(0));cpu['lscpu']=json.loads(capture(['lscpu','--json']) or '{}')
    smi=smi_path();gpu=None
    if smi:gpu=capture([smi,'-i',str(args.device),'--query-gpu=name,compute_cap,memory.total,driver_version,power.limit','--format=csv,noheader'])
    return dict(label=args.label or socket.gethostname(),cpu=cpu,gpu=gpu,os=platform.platform(),python=sys.version,meminfo=Path('/proc/meminfo').read_text(),loadavg=list(os.getloadavg()),before=gpu_sample(args.device),nvcc=capture([Path(build['installation'].get('cuda_home','/usr/local/cuda'))/'bin/nvcc','--version']))

def environment(args,build):
    env={k:v for k,v in os.environ.items() if not k.startswith(('MBS_','BEM_','OMP_','GOMP_','KMP_','MKL_','OPENBLAS_','CUDA_'))}
    env.update(build['exports'])
    env.update(OMP_NUM_THREADS=str(args.threads),OPENBLAS_NUM_THREADS='1',MKL_NUM_THREADS='1',OMP_DYNAMIC='FALSE',OMP_PROC_BIND='spread',OMP_PLACES='cores',CUDA_VISIBLE_DEVICES=str(args.device),CUDA_MODULE_LOADING='EAGER',CUDA_CACHE_PATH=str(args.output/'cuda_cache'),MBS_GPU_TIMING='1',BEM_MIXED_ITERATIVE_REFINEMENT='1')
    return env

def timed_process(command,env,directory,device,timeout):
    directory.mkdir(parents=True);samples=[];stop=threading.Event()
    def monitor():
        while not stop.is_set():
            sample=gpu_sample(device)
            if sample:samples.append(sample)
            stop.wait(1)
    thread=threading.Thread(target=monitor,daemon=True);thread.start()
    start=time.perf_counter()
    try:
        with (directory/'stdout.log').open('w') as log:
            p=subprocess.Popen(command,cwd=directory,env=env,stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
            while True:
                pid,status,usage=os.wait4(p.pid,os.WNOHANG)
                if pid:p.returncode=os.waitstatus_to_exitcode(status);break
                if time.perf_counter()-start>timeout:
                    import signal
                    os.killpg(p.pid,signal.SIGTERM)
                    try:p.wait(timeout=15)
                    except subprocess.TimeoutExpired:os.killpg(p.pid,signal.SIGKILL);p.wait()
                    raise RuntimeError('Benchmark timeout; inspect '+str(directory/'stdout.log'))
                time.sleep(.01)
            wall=time.perf_counter()-start
            if p.returncode:raise RuntimeError(f'Benchmark process exit {p.returncode}; inspect {directory}/stdout.log')
        return dict(wall_s=wall,cpu_user_s=usage.ru_utime,cpu_system_s=usage.ru_stime,peak_child_rss_MiB=usage.ru_maxrss/1024,telemetry=samples)
    finally:stop.set();thread.join(timeout=5)

def command_for(case,build,profile,threads,directory):
    args=[v.replace('{threads}',str(threads)) for v in case['arguments']]
    if case['kind']=='mbs':return [build['native_binary']]+args+['--backend','cpu' if profile=='cpu' else 'cuda','--output',str(directory/'result'),'--close']
    if case['kind']=='bem_fixed':return [build['native_binary']]+args+['--out',str(directory/'result.json')]
    return [build['python'],str(Path(build['source_root'])/'scripts/build_fmm_tmatrix.py')]+args+['--so3-threads',str(threads),'--out',str(directory/'result')]

def read_result(case,directory,profile):
    metrics={};work={};log=(directory/'stdout.log').read_text(errors='replace')
    if case['kind']=='mbs':
        file=directory/'result/result.dat';lines=file.read_text().splitlines();rows=[list(map(float,line.split())) for line in lines[1:] if line.strip()];matrix=[[r[0]]+r[2:] for r in rows]
        for key in ['Configured beam-limit hits','Hard tree-limit hits','Orientations still incomplete']:
            found=re.search(re.escape(key)+r':\s*(\d+)',log)
            if not found or int(found[1]):raise ValueError('MBS incomplete trace or missing trace status: '+key)
        count=re.search(r'Total number of body orientations:\s*(\d+)',log)
        if not count or int(count[1])!=case['work']['orientations']:raise ValueError('Wrong orientation work count')
        work=dict(orientations=int(count[1]))
        phases=directory/'result/result_phase_timings.tsv'
        if phases.exists():
            with phases.open() as f:
                for r in csv.DictReader(f,delimiter='\t'):
                    if r['phase'] in ['trace_prepare','diffraction_and_controls','gpu_diffraction_including_packing','processing']:metrics[r['phase']+'_s']=float(r['seconds'])
        kernels=re.findall(r'GPU timing diffract .*?kernels=([\d.eE+-]+)ms',log)
        if profile.startswith('gpu') and not kernels:raise ValueError('Missing native GPU diffraction timing')
        if kernels:metrics['gpu_kernels_s']=sum(map(float,kernels))/1000
    elif case['kind']=='bem_fixed':
        d=json.loads((directory/'result.json').read_text());p=d['physical'];a=p['mueller'];matrix=[[v]+[a[i][j][k] for i in range(4) for j in range(4)] for k,v in enumerate(p['theta_degrees'])]
        if not d['mbj']['fmm_residual_verified'] or max(d['mbj']['fmm_residual'],p['parallel_fmm_residual'])>case['residual_limit']:raise ValueError('BEM residual gate failed')
        work=dict(system_dofs=d['system_dofs'],mesh_triangles=d['mesh_triangles'],polarizations=2,iterations=[d['mbj']['iterations'],p['parallel_iterations']])
        if d['system_dofs']!=case['work']['system_dofs'] or d['mesh_triangles']!=case['work']['mesh_triangles']:raise ValueError('Changed BEM mesh workload')
        if not d['gpu_operator_assembly'] or d['fmm_near_precision']!='fp32':raise ValueError('Changed BEM precision/operator backend')
        metrics=dict(fmm_setup_s=d['fmm_setup_s'],mbj_setup_s=d['mbj_local_setup_s'],solve_s=d['mbj']['solve_s']+p['parallel_s'],farfield_s=p['farfield_s'],max_residual=max(d['mbj']['fmm_residual'],p['parallel_fmm_residual']))
    else:
        d=json.loads((directory/'result/summary.json').read_text());a=json.loads((directory/'result/average.json').read_text());u=a['mueller'];matrix=[[v]+[u[i][j][k] for i in range(4) for j in range(4)] for k,v in enumerate(a['theta'])]
        if not d['complete'] or d['completed_columns']!=case['work']['columns'] or d['mode_count']!=case['work']['columns']:raise ValueError('Incomplete T matrix')
        if d['maximum_strict_residual']>case['residual_limit'] or not d['pairs_this_run']:raise ValueError('T-matrix residual/cache gate failed')
        if d['operator']['system_dofs']!=case['work']['system_dofs'] or len(d['pairs_this_run'])!=case['work']['solve_pairs']:raise ValueError('Changed T-matrix work or resumed columns')
        if a.get('Euler_quadrature_nodes')!=0 or a.get('T_storage_precision')!='fp64':raise ValueError('Changed analytic SO(3) precision/method')
        work=dict(system_dofs=d['operator']['system_dofs'],columns=d['completed_columns'],solve_pairs=len(d['pairs_this_run']),iterations=[p['iterations'] for p in d['pairs_this_run']],Euler_quadrature_nodes=0)
        metrics=dict(operator_setup_s=d['operator']['operator_setup_s'],mbj_setup_s=d['operator']['mbj_setup_s'],solve_s=sum(p['solve_s'] for p in d['pairs_this_run']),farfield_s=sum(p['farfield_s'] for p in d['pairs_this_run']),analytic_so3_s=d['analytic_so3_s'],max_residual=d['maximum_strict_residual'])
    validate_matrix(matrix,case['angles'])
    if not all(math.isfinite(v) and v>=0 for v in metrics.values()):raise ValueError('Nonfinite/negative native metric')
    return matrix,metrics,work

def compare_reports(baseline,candidate):
    if not baseline.get('passed') or not candidate.get('passed'):raise ValueError('Cannot rank unvalidated results')
    rows=[]
    for b in baseline['cases']:
        matches=[c for c in candidate['cases'] if c['comparison_key']==b['comparison_key']]
        if not matches:raise ValueError('Workload/profile/thread/reference mismatch for '+b['id'])
        c=matches[0]
        if min(b['statistics']['wall_s']['n'],c['statistics']['wall_s']['n'])<3:raise ValueError('At least three measured repeats required for ranking')
        same_source=baseline['build']['numerical_source_sha256']==candidate['build']['numerical_source_sha256']
        compilers=baseline['build'].get('host_compiler_build_ids');nvcc=baseline['build'].get('installation',{}).get('nvcc')
        same_cuda=baseline.get('profile')=='cpu' or bool(nvcc and nvcc==candidate['build'].get('installation',{}).get('nvcc'))
        same_toolchain=bool(compilers and compilers==candidate['build'].get('host_compiler_build_ids') and same_cuda and baseline['build'].get('analysis_environment',{})==candidate['build'].get('analysis_environment',{}))
        rows.append(dict(case=b['id'],baseline_label=baseline['hardware']['label'],candidate_label=candidate['hardware']['label'],speedup_baseline_over_candidate=b['statistics']['wall_s']['median']/c['statistics']['wall_s']['median'],same_numerical_source=same_source,same_recorded_toolchain=same_toolchain,scope='hardware/platform comparison' if same_source and same_toolchain else 'software/toolchain and hardware comparison',baseline_relative_MAD=b['statistics']['wall_s']['relative_MAD'],candidate_relative_MAD=c['statistics']['wall_s']['relative_MAD']))
    return rows

def main():
    parser=argparse.ArgumentParser(description=__doc__);sub=parser.add_subparsers(dest='action',required=True)
    compare=sub.add_parser('compare');compare.add_argument('baseline',type=Path);compare.add_argument('candidate',type=Path);compare.add_argument('--output',type=Path)
    suite=json.loads((SUITE/'suite.json').read_text())
    for action in ['run','reference']:
        p=sub.add_parser(action);p.add_argument('--output',required=True,type=Path);p.add_argument('--profile',choices=list(suite['profiles']),default=suite['default_profile']);p.add_argument('--case',choices=['all']+[c['id'] for c in suite['cases']],default='all');p.add_argument('--prefix',type=Path);p.add_argument('--binary',type=Path);p.add_argument('--python',type=Path);p.add_argument('--threads',type=int,default=8);p.add_argument('--device',type=int,default=0);p.add_argument('--warmups',type=int,default=1);p.add_argument('--repeats',type=int,default=5);p.add_argument('--reference-dir',type=Path,default=SUITE/'reference');p.add_argument('--timeout',type=int,default=600);p.add_argument('--label');p.add_argument('--allow-busy-gpu',action='store_true')
    args=parser.parse_args()
    if args.action=='compare':
        result=compare_reports(json.loads(args.baseline.read_text()),json.loads(args.candidate.read_text()));print(json.dumps(result,indent=2))
        if args.output:write(args.output,result)
        return
    if min(args.threads,args.repeats,args.timeout)<1 or args.warmups<1 or args.device<0:parser.error('Positive counts and at least one warmup required')
    if args.action=='run' and args.repeats<3:parser.error('Use at least three measured repeats; default is five')
    args.output=args.output.expanduser().absolute()
