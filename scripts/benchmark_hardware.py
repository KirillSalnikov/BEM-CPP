    env=environment(args,build);controlled={k:env[k] for k in ['OMP_NUM_THREADS','OPENBLAS_NUM_THREADS','MKL_NUM_THREADS','OMP_DYNAMIC','OMP_PROC_BIND','OMP_PLACES','CUDA_MODULE_LOADING','MBS_GPU_TIMING','BEM_MIXED_ITERATIVE_REFINEMENT']}
